"""HTML and CSV report rendering for BH FTMO Phase 3 backtest results.

Standalone per decision 15D: this module does not depend on the equity-side
reporting stack. HTML output is self-contained with inline CSS and base64 PNG
charts generated by matplotlib.
"""

from __future__ import annotations

# pylint: disable=too-many-arguments,too-many-locals

